def localize_th_ability_source(
    raw: str | None,
    char_map: dict[str, str],
    weapon_map: dict[str, str],
    class_translator,
) -> str | None:
    s = (raw or "").strip()
    if not s or s in ("-", "--", "N/A"):
        return None
    # Translate common phrases cleanly
    out = s
    out = re.sub(r"\((\d+)\s*class\s*Exp\)", r"（精通需 \1 兵种经验）", out, flags=re.IGNORECASE)
    out = re.sub(r"\(Prologue[–-]Chapter\s*(\d+)\)", r"（序章～第 \1 章）", out, flags=re.IGNORECASE)
    out = re.sub(r"\(Chapter\s*(\d+)\s*onwards?\)", r"（第 \1 章起）", out, flags=re.IGNORECASE)
    out = re.sub(r"\(Part\s*II\)", "（第二部）", out, flags=re.IGNORECASE)
    out = re.sub(r"\(Part\s*I\)", "（第一部）", out, flags=re.IGNORECASE)
    out = re.sub(r"\bEnemy[- ]only\b", "敌方限定", out, flags=re.IGNORECASE)
    out = re.sub(r"\bEnemies\b", "敌方单位", out, flags=re.IGNORECASE)
    out = re.sub(r"\bMonsters?\b", "魔物单位", out, flags=re.IGNORECASE)
    out = re.sub(r"\bBudding Talent\b", "才能绽放", out, flags=re.IGNORECASE)
    out = re.sub(r"\bSkill level\b", "技能等级", out, flags=re.IGNORECASE)
    out = re.sub(r"\bWhite Heron Cup\b", "白鹭杯优胜", out, flags=re.IGNORECASE)
    out = re.sub(r"\bSaint\b", "圣者", out)
    # Split comma-separated lists of classes / characters / skill levels
    parts = [p.strip() for p in re.split(r"\s*,\s*|\s*;\s*", out) if p.strip()]
    zh_parts: list[str] = []
    for part in parts:
        # Handle "Name（...）" suffix preservation
        suffix = ""
        base = part
        m_suf = re.match(r"^(.+?)\s*([（(].+[）)])$", part)
        if m_suf:
            base = m_suf.group(1).strip()
            suffix = m_suf.group(2).strip().replace("(", "（").replace(")", "）")
        # Skill rank requirement like "Sword E+" / "Heavy Armor C"
        m_rk = re.match(r"^(Sword|Lance|Axe|Bow|Brawling|Reason|Faith|Authority|Heavy Armor|Riding|Flying)\s+([A-ES][+-]?)$", base)
        if m_rk:
            w_zh = weapon_map.get(m_rk.group(1), m_rk.group(1))
            zh_parts.append(f"{w_zh} {m_rk.group(2)}{suffix}")
            continue
        if base in char_map:
            zh_parts.append(f"{char_map[base]}{suffix}")
            continue
        cls_zh = class_translator(base)
        if cls_zh and cls_zh != base:
            zh_parts.append(f"{cls_zh}{suffix}")
            continue
        # Replace known character names inline (e.g. "Byleth / Jeritza")
        replaced = base
        for en_k, zh_v in sorted(char_map.items(), key=lambda x: -len(x[0])):
            if len(en_k) >= 3 and re.search(rf"\b{re.escape(en_k)}\b", replaced):
                replaced = re.sub(rf"\b{re.escape(en_k)}\b", zh_v, replaced)
        for en_w, zh_w in sorted(weapon_map.items(), key=lambda x: -len(x[0])):
            if len(en_w) >= 3 and re.search(rf"\b{re.escape(en_w)}\b", replaced):
                replaced = re.sub(rf"\b{re.escape(en_w)}\b", zh_w, replaced)
        zh_parts.append(f"{replaced}{suffix}")
    return "、".join(dict.fromkeys(zh_parts)) if zh_parts else None


def translate_th_ability_effect(name_en: str, fallback_en: str) -> str:
    if name_en in TH_ABILITY_EFFECT_ZH:
        return TH_ABILITY_EFFECT_ZH[name_en]
    # Try case-insensitive match
    low = name_en.strip().lower()
    for k, v in TH_ABILITY_EFFECT_ZH.items():
        if k.lower() == low:
            return v
    # Check Prowess pattern
    for base, levels in TH_PROWESS_LEVELS.items():
        for _, en_lv, _, eff_zh in levels:
            if en_lv.lower() == low:
                return eff_zh
    # Fallback basic replacement so no raw English leaks
    s = (fallback_en or "").strip()
    if s.startswith("Allows unit to cast "):
        m = re.match(r"Allows unit to cast (.+?)\.", s)
        spell = m.group(1) if m else ""
        return f"无需习得即可使用魔法「{spell}」；若已习得则使用次数翻倍。"
    return s


